import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
  alias(libs.plugins.android.application)
  alias(libs.plugins.jetbrains.kotlin.android)
  alias(libs.plugins.compose.compiler)
}

val localProperties =
    Properties().apply {
      val file = rootDir.resolve("local.properties")
      if (file.exists()) {
        file.inputStream().use { load(it) }
      }
    }

android {
  namespace = "com.meta.wearable.dat.externalsampleapps.cameraaccess"
  compileSdk = 36

  buildFeatures { buildConfig = true }

  defaultConfig {
    applicationId = "com.glasseslive.hq"
    minSdk = 31
    targetSdk = 36
    versionCode = 4
    versionName = "1.3"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

    // Meta Wearables Device Access Toolkit Setup
    // Without Developer Mode, these values need to be set with credentials from the app registered
    // in Wearables Developer Center
    manifestPlaceholders["mwdat_application_id"] =
        localProperties.getProperty("mwdat_application_id", "0")
    manifestPlaceholders["mwdat_client_token"] =
        localProperties.getProperty("mwdat_client_token", "0")
  }

  // Release signing comes only from environment variables (GitHub Actions secrets). The key is
  // never stored in the repo. Without them (local builds, forks) the release APK is signed with
  // the standard debug key instead, which can't install over official builds.
  val releaseKeystore = System.getenv("GLASSESLIVE_KEYSTORE_FILE")?.let { file(it) }
  val hasReleaseKey = releaseKeystore?.exists() == true
  signingConfigs {
    if (hasReleaseKey) {
      create("release") {
        storeFile = releaseKeystore
        storePassword = System.getenv("GLASSESLIVE_KEYSTORE_PASSWORD")
        keyAlias = System.getenv("GLASSESLIVE_KEY_ALIAS") ?: "glasseslive"
        keyPassword = System.getenv("GLASSESLIVE_KEYSTORE_PASSWORD")
      }
    }
  }

  buildTypes {
    release {
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig =
          if (hasReleaseKey) signingConfigs.getByName("release")
          else signingConfigs.getByName("debug")
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
  }
  packaging { resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" } }
}

kotlin { compilerOptions { jvmTarget = JvmTarget.JVM_17 } }

